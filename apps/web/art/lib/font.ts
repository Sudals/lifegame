export function textWidth(s: string, scale = 1): number {
  return s.length * 6 * scale - scale;
}

export function text(cv: PixelCanvas, s: string, x: number, y: number, col: number, scale = 1): void {
  let cx = x;
  for (const ch of s.toUpperCase()) {
    const g = G[ch] ?? G['?']!;
    g.forEach((row, j) => {
      for (let i = 0; i < 5; i++) if (row[i] === '#') cv.rect(cx + i * scale, y + j * scale, scale, scale, col);
    });
    cx += 6 * scale;
  }
}
